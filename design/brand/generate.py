"""Generates Setu's icon files from one definition of the mark.

Writes the dark and light SVGs in this folder and the agent's launcher icon drawables. PNG and ICO exports
are rendered from the SVGs by render.py, which needs Chromium.

    python3 design/brand/generate.py
"""

import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE.parents[1] / "apps/agent/src/main/res"

INK = "#15141A"
CREAM = "#F5ECDC"
SIGNAL = "#FF3B2F"

# The mark, "Soft Top": a 9 × 7 grille on an 8-unit grid inside a 100-unit tile, with an arch cut
# from the bottom edge and the two top corners dropped so the silhouette reads as a headset.
DOT_R = 2.8
LIGHT = (74, 26)


def mark_dots():
    dots = []
    for y in range(26, 75, 8):
        for x in range(18, 83, 8):
            if math.hypot(x - 50, y - 78) < 23:
                continue
            if y == 26 and x in (18, 82):
                continue
            dots.append((x, y))
    return dots


# The 16 px cut, drawn on the pixel grid: two-pixel dots on a three-pixel pitch.
CUT_16 = {3: (5, 8, 11), 6: (2, 5, 8, 11, 14), 9: (2, 5, 11, 14), 12: (2, 5, 11, 14)}
CUT_16_LIGHT = (11, 3)


def superellipse(size, n=5, steps=240):
    """Continuous-corner tile outline filling a size × size square."""
    h = size / 2
    pts = []
    for i in range(steps):
        t = i / steps * 2 * math.pi
        c, s = math.cos(t), math.sin(t)
        x = h + h * math.copysign(abs(c) ** (2 / n), c)
        y = h + h * math.copysign(abs(s) ** (2 / n), s)
        pts.append(f"{x:.2f} {y:.2f}")
    return "M" + "L".join(pts) + "Z"


# Each theme is the tile and grille colours, plus the hairline that keeps the tile's edge visible
# on a background of the same tone. Signal stays the same in both.
THEMES = {
    "dark": {"tile": INK, "dot": CREAM, "edge": 'stroke="#fff" stroke-opacity=".14"'},
    "light": {"tile": CREAM, "dot": INK, "edge": f'stroke="{INK}" stroke-opacity=".08"'},
}


def circles(dots, r, light, dot=CREAM):
    return "".join(
        f'<circle cx="{x}" cy="{y}" r="{r}" fill="{SIGNAL if (x, y) == light else dot}"/>'
        for x, y in dots
    )


def svg(size, body, label):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" '
        f'width="{size}" height="{size}" '
        f'role="img" aria-label="{label}">{body}</svg>\n'
    )


def tile_svg(theme):
    t, edge = THEMES[theme], superellipse(100)
    return svg(
        100,
        f'<path d="{edge}" fill="{t["tile"]}"/>{circles(mark_dots(), DOT_R, LIGHT, t["dot"])}'
        f'<path d="{edge}" fill="none" {t["edge"]} stroke-width=".9"/>',
        "Setu",
    )


def mark_svg(theme):
    return svg(100, circles(mark_dots(), DOT_R, LIGHT, THEMES[theme]["dot"]), "Setu")


def cut16_svg(theme):
    t, edge = THEMES[theme], superellipse(16)
    dots = [(x, y) for y, xs in CUT_16.items() for x in xs]
    return svg(16, f'<path d="{edge}" fill="{t["tile"]}"/>{circles(dots, 1, CUT_16_LIGHT, t["dot"])}', "Setu")


# Android adaptive icon. The layer is 108 dp with a 66 dp safe circle; the mark is scaled about
# the centre so its farthest dot stays inside that circle.
def circle_path(x, y, r):
    return f"M{x - r:g},{y}a{r:g},{r:g} 0 1,0 {2 * r:g},0a{r:g},{r:g} 0 1,0 {-2 * r:g},0"


def foreground_xml(mono):
    dots = mark_dots()
    reach = max(math.hypot(abs(x - 50) + DOT_R, abs(y - 50) + DOT_R) for x, y in dots)
    scale = round(33 / reach, 4)
    shift = round(54 - 50 * scale, 4)
    cream = [d for d in dots if d != LIGHT]
    paths = [(CREAM, "".join(circle_path(x, y, DOT_R) for x, y in cream))]
    paths.append((SIGNAL, circle_path(*LIGHT, DOT_R)))
    if mono:
        paths = [("#FFFFFFFF", paths[0][1] + paths[1][1])]
    body = "\n".join(
        f'        <path\n            android:fillColor="{color}"\n            android:pathData="{data}" />'
        for color, data in paths
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/brand/generate.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="{scale}"
        android:scaleY="{scale}"
        android:translateX="{shift}"
        android:translateY="{shift}">
{body}
    </group>
</vector>
"""


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/brand/generate.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/setu_ink" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""

COLORS = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Setu's brand colours; see design/brand/README.md. Generated by design/brand/generate.py. -->
<resources>
    <color name="setu_ink">{INK}</color>
    <color name="setu_cream">{CREAM}</color>
    <color name="setu_signal">{SIGNAL}</color>
</resources>
"""


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(path.relative_to(HERE.parents[1]))


if __name__ == "__main__":
    for theme in THEMES:
        write(HERE / f"setu-icon-{theme}.svg", tile_svg(theme))
        write(HERE / f"setu-mark-{theme}.svg", mark_svg(theme))
        write(HERE / f"setu-icon-16-{theme}.svg", cut16_svg(theme))
    write(RES / "drawable/ic_launcher_foreground.xml", foreground_xml(mono=False))
    write(RES / "drawable/ic_launcher_monochrome.xml", foreground_xml(mono=True))
    write(RES / "mipmap-anydpi/ic_launcher.xml", ADAPTIVE)
    write(RES / "values/colors.xml", COLORS)
